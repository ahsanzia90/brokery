import { chromium, devices } from "@playwright/test";
import { execSync } from "node:child_process";
const base = "http://localhost:3000";
const out = "screenshots/final";
const mint = (phone) => execSync(`npx tsx scripts/dev-session.ts --phone ${phone}`, { encoding: "utf8" }).match(/ml_session=(\S+)/)[1];
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH || undefined });
const ck = (name, value) => ({ name, value, domain: "localhost", path: "/" });
async function shot(opts, path, name, full = false) {
  const ctx = await browser.newContext(opts.mobile ? { ...devices["Pixel 7"] } : { viewport: { width: 1366, height: 860 } });
  const cookies = [];
  if (opts.phone) cookies.push(ck("ml_session", mint(opts.phone)));
  if (opts.lang) cookies.push(ck("ml_lang", opts.lang));
  if (cookies.length) await ctx.addCookies(cookies);
  const page = await ctx.newPage();
  await page.goto(base + path, { waitUntil: "networkidle" });
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${out}/${name}.png`, fullPage: full });
  await ctx.close();
}
