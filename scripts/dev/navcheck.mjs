import { chromium, devices } from "@playwright/test";
import { execSync } from "node:child_process";
const mint = (p) => execSync(`npx tsx scripts/dev-session.ts --phone ${p}`, { encoding: "utf8" }).match(/ml_session=(\S+)/)[1];
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH });
const ctx = await browser.newContext({ viewport: { width: 1366, height: 860 } });
await ctx.addCookies([{ name: "ml_session", value: mint("+923000000001"), domain: "localhost", path: "/" }]);
const page = await ctx.newPage();
await page.goto("http://localhost:3000/prices", { waitUntil: "networkidle" });
console.log("prices nav active:", await page.locator('nav[aria-label="Main"] a[aria-current="page"]').textContent());
await page.getByRole("link", { name: /Commodities/ }).first().click();
await page.waitForURL(/\/categories/);
await page.waitForTimeout(500);
console.log("after client nav active:", await page.locator('nav[aria-label="Main"] a[aria-current="page"]').textContent());
await page.getByRole("link", { name: /^Admin$/ }).first().click();
await page.waitForURL(/\/admin/);
await page.waitForTimeout(800);
console.log("site header present in admin:", await page.locator('header nav[aria-label="Main"]').count());
console.log("admin active:", await page.locator('nav[aria-label="Admin"] a[aria-current="page"]').textContent());
await page.getByRole("link", { name: /Market prices/ }).first().click();
await page.waitForURL(/\/admin\/prices/);
await page.waitForTimeout(800);
console.log("admin active after nav:", (await page.locator('nav[aria-label="Admin"] a[aria-current="page"]').allTextContents()).join("|"));
console.log("crumbs:", (await page.locator('nav[aria-label="Breadcrumb"]').textContent()));
await page.screenshot({ path: "screenshots/nav-admin-prices.png" });
await ctx.close();
const guest = await browser.newContext({ viewport: { width: 1366, height: 860 } });
const g = await guest.newPage();
const r = await g.goto("http://localhost:3000/admin", { waitUntil: "networkidle" });
console.log("guest /admin ->", g.url());
await g.screenshot({ path: "screenshots/admin-login.png" });
await g.goto("http://localhost:3000/rfq/new?commodity=rice", { waitUntil: "networkidle" });
await g.waitForTimeout(800);
await g.screenshot({ path: "screenshots/rfq-form-spacing.png", fullPage: true });
await browser.close();
